const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const fs=require("fs"),path=require("path"),{pathToFileURL}=require("url"),assert=require("assert");
(async()=>{
const base=path.resolve(__dirname);
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || chromium.executablePath(),headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];const remote=[];page.on("pageerror",e=>errors.push(e.message));page.on("request",r=>{if(r.url().startsWith("http"))remote.push(r.url())});
const folder=path.join(base,"recordings/cetp-torcetrapib-v2");
await page.goto(pathToFileURL(path.join(folder,"index.html")).href);
await page.getByRole("tab",{name:"Genetic Insights",exact:true}).click();
assert.equal(await page.locator(".event").count(),11);
assert.equal(await page.locator(".stage-human_genetics").count(),1);
assert.equal(await page.locator(".stage-preclinical .event").count(),2);
assert((await page.locator("#timeline-capture").innerText()).includes("Inherited CETP deficiency"));
await page.locator('[data-event="genetic-comparison"]').click();
assert((await page.locator("#event-detail").innerText()).includes("2009-12-21"));
assert((await page.locator("#timeline-title").innerText()).includes("Torcetrapib"));
assert(!(await page.locator("#status").innerText()).includes("Approved"));
await page.screenshot({path:path.join(folder,"recording-preview.png"),fullPage:true});
await page.locator("#timeline-capture").screenshot({path:path.join(folder,"timeline.png")});
await page.getByRole("tab",{name:"Slack preview",exact:true}).click();
assert((await page.locator("#slack-content").innerText()).includes("2009-12-21"));
assert((await page.locator("#slack-content").innerText()).includes("Pfizer"));
await page.getByRole("tab",{name:"What's next",exact:true}).click();
assert((await page.locator("#modules").innerText()).includes("Awaiting accepted output"));
await page.getByRole("button",{name:"Presentation mode",exact:true}).click();
assert(await page.locator("body").evaluate(el=>el.classList.contains("presentation")));
await page.locator("#load").setInputFiles({name:"bad.json",mimeType:"application/json",buffer:Buffer.from('{"schema_version":"1.0"}')});
assert(await page.locator("#error").isVisible());
assert((await page.locator("#pair").innerText()).includes("CETP"));
await page.locator("#load").setInputFiles(path.join(base,"snapshots/mvp1-cetp-evacetrapib-2026-09-12-v2.json"));
await page.getByRole("tab",{name:"Genetic Insights",exact:true}).click();
assert((await page.locator("#timeline-title").innerText()).includes("Evacetrapib"));
await page.setViewportSize({width:390,height:844});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
const ev=path.join(base,"recordings/cetp-evacetrapib-v2");
await page.setViewportSize({width:1440,height:1100});
await page.goto(pathToFileURL(path.join(ev,"index.html")).href+"#insights");
await page.locator('[data-event="programme-stop"]').click();
await page.screenshot({path:path.join(ev,"recording-preview.png"),fullPage:true});
await page.locator("#timeline-capture").screenshot({path:path.join(ev,"timeline.png")});
assert.equal(errors.length,0,JSON.stringify(errors));
assert.equal(remote.length,0,JSON.stringify(remote));
await browser.close();
fs.writeFileSync(path.join(base,"UI_VERIFICATION.json"),JSON.stringify({checked_at:new Date().toISOString(),cases:2,event_counts:{torcetrapib:11,evacetrapib:10},checks:["required human-genetic and preclinical stages","timeline selection","case-specific title/status","Slack preview","module status","presentation mode","invalid snapshot preservation","valid snapshot import","390px layout","offline no remote requests"],javascript_errors:errors,remote_requests:remote},null,2));
console.log("PASS: two case pages; timeline, tabs, file import, mobile layout; no JS errors or network requests.");
})().catch(e=>{console.error(e);process.exit(1)});
